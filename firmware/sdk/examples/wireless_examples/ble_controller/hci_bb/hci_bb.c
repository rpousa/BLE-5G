/* nrlink v9: jump to the ROM ISP bootloader with a quiet core (same sequence as nrlink's enter_isp). Both UARTs are
 * reset so the ROM can autobaud on the VCOM (blhost). Used by HCI vendor command 0xFDB1 and the VCOM text "isp". */
static void Hcibb_EnterIsp(void)
{
    static const uint32_t bootArg = ROM_ISP_BOOT_ARG;
    void (*runBootloader)(void *arg) = *(void (**)(void *))ROM_API_TREE_ADDR;
    LPUART_Type *const uarts[2] = {LPUART0, LPUART1};
    __disable_irq();
    SysTick->CTRL = 0U;
    for (uint32_t i = 0U; i < (sizeof(NVIC->ICER) / sizeof(NVIC->ICER[0])); i++)
    {
        NVIC->ICER[i] = 0xFFFFFFFFU;
        NVIC->ICPR[i] = 0xFFFFFFFFU;
    }
    for (uint32_t i = 0U; i < 2U; i++)
    {
        if ((uarts[i]->CTRL & (LPUART_CTRL_TE_MASK | LPUART_CTRL_RE_MASK)) == 0U) { continue; }
        uarts[i]->CTRL  = 0U;
        uarts[i]->FIFO  = LPUART_FIFO_TXFLUSH_MASK | LPUART_FIFO_RXFLUSH_MASK;
        uarts[i]->WATER = 0U;
        uarts[i]->MODIR = 0U;
        uarts[i]->STAT  = uarts[i]->STAT;
    }
    SCB->VTOR = 0U;
    __DSB();
    __ISB();
    runBootloader((void *)&bootArg);
    for (;;) { }
}

/* nrlink v9/v10: the VCOM at 115200, polled from the main loop (and a 1.5 s window at boot); only "isp" is
 * understood (board.sh isp). Note: OSA_SysTickHook never runs in this build (FSL_OSA_BM_TIMER_NONE). */
static volatile uint8_t mVcomReady;
static void Vcom_Init(void)
{
    lpuart_config_t cfg;
    /* v10: name LPUART1 explicitly. BOARD_DEBUG_UART_CLK comes from the common board.h, where the debug UART
     * defaults to instance 0: v9 set up LPUART0's clock (the HCI UART) and left LPUART1 without one. */
    CLOCK_SetIpSrc(kCLOCK_Lpuart1, (clock_ip_src_t)BOARD_UART_CLKSRC);
    CLOCK_EnableClockLPMode(kCLOCK_Lpuart1, kCLOCK_IpClkControl_fun3);
    BOARD_InitPinLPUART1_RX();
    BOARD_InitPinLPUART1_TX();
    LPUART_GetDefaultConfig(&cfg);
    cfg.baudRate_Bps = 115200U;
    cfg.enableTx     = true;
    cfg.enableRx     = true;
    if (LPUART_Init(VCOM_UART, &cfg, CLOCK_GetIpFreq(kCLOCK_Lpuart1)) == kStatus_Success) { mVcomReady = 1U; }
}

static void Vcom_Poll(void)
{
    static uint8_t matched;
    static const char cmd[] = "isp";
    if (mVcomReady == 0U) { return; }
    if ((VCOM_UART->STAT & LPUART_STAT_OR_MASK) != 0U) { VCOM_UART->STAT = LPUART_STAT_OR_MASK; }
    while ((VCOM_UART->STAT & LPUART_STAT_RDRF_MASK) != 0U)
    {
        char c = (char)(VCOM_UART->DATA & 0xFFU);
        matched = (c == cmd[matched]) ? (uint8_t)(matched + 1U) : ((c == cmd[0]) ? 1U : 0U);
        if (matched == 3U)
        {
            static const char reply[] = "ISP\r\n";
            for (uint32_t i = 0U; i < sizeof(reply) - 1U; i++)
            {
                while ((VCOM_UART->STAT & LPUART_STAT_TDRE_MASK) == 0U) { }
                VCOM_UART->DATA = (uint8_t)reply[i];
            }
            while ((VCOM_UART->STAT & LPUART_STAT_TC_MASK) == 0U) { }
            Hcibb_EnterIsp();
        }
    }
}

static void Hcibb_IrqPrioritiesBelowTick(void);
void OSA_SysTickHook(uint32_t *frame)
{
    static uint32_t lastLoop, stillMs, rxWaitMs, ms;
    if ((++ms % 1000U) == 0U) { Hcibb_IrqPrioritiesBelowTick(); }
    Vcom_Poll();
    /* v5: input sitting in the RX FIFO (or an overrun) for 1 s means nobody services the UART */
    if ((((HCI_UART->WATER & LPUART_WATER_RXCOUNT_MASK) >> LPUART_WATER_RXCOUNT_SHIFT) != 0U) ||
        ((HCI_UART->STAT & LPUART_STAT_OR_MASK) != 0U))
    {
        rxWaitMs++;
        if ((rxWaitMs % 2000U) == 1000U)
        {
            Diag_Report(5U, frame[6], HCI_UART->STAT, HCI_UART->CTRL, HCI_UART->WATER);
        }
    }
    else
    {
        rxWaitMs = 0U;
    }
    if (gOsaLoopCount != lastLoop)
    {
        lastLoop = gOsaLoopCount;
        stillMs  = 0U;
        return;
    }
    stillMs++;
    if ((stillMs >= 2000U) && ((stillMs % 2000U) == 0U))
    {
        Diag_Report((mDiagKind != 0U) ? mDiagKind : 3U, frame[6], frame[5], frame[7],
                    (mDiagKind != 0U) ? mDiagInfo : stillMs);
        /* v12: which interrupts are active (IABR: an interrupt that never returns stays active) and ICSR */
        Diag_Report(7U, NVIC->IABR[0], NVIC->IABR[1], NVIC->IABR[2], SCB->ICSR);
    }
}

/* v12: SysTick (OSA's 1 kHz tick, which calls OSA_SysTickHook above) on the highest priority, every other interrupt
 * one level below it, so a handler that never returns is preempted and reported (kinds 3 and 7) while the main loop
 * is stuck. The hook re-applies the priorities every second: drivers set their own as they start. */
static void Hcibb_IrqPrioritiesBelowTick(void)
{
    for (uint32_t i = 0U; i < (uint32_t)(NUMBER_OF_INT_VECTORS - 16); i++)
    {
        if (NVIC_GetPriority((IRQn_Type)i) == 0U) { NVIC_SetPriority((IRQn_Type)i, 1U); }
    }
    NVIC_SetPriority(SysTick_IRQn, 0U);
}


void HardFault_C(uint32_t *frame)
{
    for (;;)
    {
        Diag_Report(2U, frame[6], frame[5], frame[7], SCB->CFSR);
        for (volatile uint32_t i = 0U; i < 30000000U; i++) { }
    }
}

void HardFault_Handler(void) __attribute__((naked));
void HardFault_Handler(void)
{
    __asm volatile(
        "tst lr, #4      \n"
        "ite eq          \n"
        "mrseq r0, msp   \n"
        "mrsne r0, psp   \n"
        "b HardFault_C   \n");
}

/* v8: board RGB LED (active low: PTA19 green, PTA20 blue, PTA21 red) steady green, so the Bluetooth boards are
 * told apart from the nrlink boards (blue/red) at a glance. */
static void Hcibb_LedGreen(void)
{
    const uint32_t g = 1UL << 19, b = 1UL << 20, r = 1UL << 21;
    CLOCK_EnableClock(kCLOCK_PortA);
    CLOCK_EnableClock(kCLOCK_GpioA);
    (void)g;                 /* v9: PTA19 is LPUART0_RTS_b, so green is lit whenever the board can take HCI input */
    PORTA->PCR[20] = PORT_PCR_MUX(1);
    PORTA->PCR[21] = PORT_PCR_MUX(1);
    GPIOA->PSOR = b | r;     /* blue and red off */
    GPIOA->PDDR |= b | r;
}

